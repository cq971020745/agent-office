#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""检查并补齐紫金私网 WPS 365 环境变量（Windows / macOS）。

用法:
    python <本目录>/run.py status
    python <本目录>/run.py ensure
    python <本目录>/run.py ensure --refresh

不打印 WPS_SID。写入：
  1. 当前进程环境变量
  2. 用户级环境变量（Windows 注册表 / macOS launchctl）
  3. ~/.wps365/env.json（供同会话 365 skill 读取）
"""
import argparse
import json
import os
import platform
import shlex
import subprocess
import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8")

HERE = Path(__file__).resolve().parent
WPS365_SKILL_ROOT = HERE.parent / "wps365-skill"
REQUIREMENTS = HERE / "requirements.txt"
SYSTEM = platform.system()


def _load_sidecar_mod():
    sidecar_py = WPS365_SKILL_ROOT / "env_sidecar.py"
    if str(WPS365_SKILL_ROOT) not in sys.path:
        sys.path.insert(0, str(WPS365_SKILL_ROOT))
    if not sidecar_py.is_file():
        raise FileNotFoundError("找不到 env_sidecar.py: %s" % sidecar_py)
    import env_sidecar  # noqa: WPS433

    return env_sidecar


def _set_user_env_windows(name, value):
    import ctypes
    import winreg

    key = winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment", 0, winreg.KEY_SET_VALUE)
    try:
        winreg.SetValueEx(key, name, 0, winreg.REG_SZ, value)
    finally:
        winreg.CloseKey(key)
    HWND_BROADCAST = 0xFFFF
    WM_SETTINGCHANGE = 0x001A
    SMTO_ABORTIFHUNG = 0x0002
    ctypes.windll.user32.SendMessageTimeoutW(
        HWND_BROADCAST,
        WM_SETTINGCHANGE,
        0,
        "Environment",
        SMTO_ABORTIFHUNG,
        5000,
        None,
    )


def _set_user_env_macos(name, value):
    subprocess.run(["launchctl", "setenv", name, value], check=False)


def _write_unix_env_sh(values):
    env_sh = Path.home() / ".wps365" / "env.sh"
    env_sh.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# generated by wps365-env; do not commit",
        "export WPS_SID=%s" % shlex.quote(values["WPS_SID"]),
        "export PRIVATE=%s" % shlex.quote(values["PRIVATE"]),
        "export X_ORIGIN=%s" % shlex.quote(values["X_ORIGIN"]),
        "",
    ]
    env_sh.write_text("\n".join(lines), encoding="utf-8")
    try:
        os.chmod(env_sh, 0o600)
    except OSError:
        pass


def _set_user_env(name, value):
    os.environ[name] = value
    if SYSTEM == "Windows":
        _set_user_env_windows(name, value)
    elif SYSTEM == "Darwin":
        _set_user_env_macos(name, value)


def _persist(values, sidecar_mod):
    sidecar_mod.save_sidecar(values)
    for key in sidecar_mod.SIDECAR_KEYS:
        _set_user_env(key, values[key])
    if SYSTEM == "Darwin":
        _write_unix_env_sh(values)
    sidecar_mod.apply_sidecar_env()


def _verify_session():
    """用当前进程环境调用 /v7/users/current，不输出 SID。"""
    if str(WPS365_SKILL_ROOT) not in sys.path:
        sys.path.insert(0, str(WPS365_SKILL_ROOT))
    from wpsv7client import WpsV7Client, get_current_user

    resp = get_current_user(WpsV7Client())
    if not isinstance(resp, dict):
        return {"api_ok": False, "api_code": None, "user_name": None, "api_msg": "响应不是 JSON"}
    code = resp.get("code")
    data = resp.get("data") if isinstance(resp.get("data"), dict) else {}
    name = (
        data.get("user_name")
        or data.get("alias_name")
        or data.get("nick_name")
        or data.get("name")
        or ""
    )
    ok = code == 0
    return {
        "api_ok": ok,
        "api_code": code,
        "user_name": name or None if ok else None,
        "api_msg": None if ok else (resp.get("msg") or resp.get("message") or "调用失败")[:200],
    }


def _report(ok, payload):
    payload.setdefault("platform", SYSTEM)
    print(json.dumps(payload, ensure_ascii=False, indent=2))
    return 0 if ok else 1


def _payload_base(snap):
    return {
        "wps_sid_set": snap["wps_sid_set"],
        "private": snap["private"] or None,
        "x_origin": snap["x_origin"] or None,
        "cloud_ide": snap["cloud_ide"],
        "sidecar_exists": snap["sidecar_exists"],
    }


def cmd_status(sidecar_mod):
    sidecar_mod.apply_sidecar_env()
    snap = sidecar_mod.env_snapshot()
    ready = sidecar_mod.is_private_ready(snap)
    payload = {
        "ok": ready,
        "ready": ready,
        "action": "status",
        "message": "环境已就绪" if ready else "环境不完整，请执行 ensure",
    }
    payload.update(_payload_base(snap))
    if ready:
        payload.update(_verify_session())
        if not payload["api_ok"]:
            payload["ok"] = False
            payload["message"] = "环境变量在，但接口校验失败，请 ensure --refresh。%s" % (
                payload.get("api_msg") or ""
            )
    return _report(payload["ok"], payload)


def _import_from_client(sidecar_mod):
    if str(HERE) not in sys.path:
        sys.path.insert(0, str(HERE))
    from extract import extract_session, zjxiezuo_running

    values = extract_session()
    running = zjxiezuo_running()
    persist_values = {
        "WPS_SID": values["WPS_SID"],
        "PRIVATE": values["PRIVATE"],
        "X_ORIGIN": values["X_ORIGIN"],
    }
    _persist(persist_values, sidecar_mod)
    verify = _verify_session()
    ok = bool(verify.get("api_ok"))
    payload = {
        "ok": ok,
        "ready": ok,
        "action": "imported",
        "source": "zjxiezuo",
        "wps_sid_set": True,
        "private": persist_values["PRIVATE"],
        "x_origin": persist_values["X_ORIGIN"],
        "zjxiezuo_running": running,
        "profile_root": values.get("profile_root"),
        "message": (
            "已从紫金协作导入会话，接口校验通过"
            if ok
            else "已导入会话，但接口校验失败：%s" % (verify.get("api_msg") or "")
        ),
    }
    payload.update(verify)
    return _report(ok, payload)


def cmd_ensure(sidecar_mod, refresh):
    sidecar_mod.apply_sidecar_env()
    snap = sidecar_mod.env_snapshot()
    ready = sidecar_mod.is_private_ready(snap)

    if ready and not refresh:
        verify = _verify_session()
        if verify.get("api_ok"):
            payload = {
                "ok": True,
                "ready": True,
                "action": "unchanged",
                "source": "env",
                "message": "环境已就绪，接口校验通过",
            }
            payload.update(_payload_base(snap))
            payload.update(verify)
            return _report(True, payload)
        # 环境在但会话失效，自动从客户端重导
        refresh = True

    if SYSTEM not in ("Windows", "Darwin"):
        return _report(
            False,
            {
                "ok": False,
                "ready": False,
                "action": "unsupported",
                "message": "紫金协作会话导入仅支持 Windows 与 macOS，当前: %s" % SYSTEM,
            },
        )

    try:
        return _import_from_client(sidecar_mod)
    except ImportError as exc:
        return _report(
            False,
            {
                "ok": False,
                "ready": False,
                "action": "failed",
                "message": "缺少依赖 %s。请执行: python -m pip install -r %s" % (exc, REQUIREMENTS),
            },
        )
    except Exception as exc:
        if str(HERE) not in sys.path:
            sys.path.insert(0, str(HERE))
        try:
            from extract import zjxiezuo_running
            running = zjxiezuo_running()
        except Exception:
            running = False
        hint = str(exc)
        if not running:
            hint += " 当前未检测到紫金协作进程，请先打开并登录后再试。"
        return _report(
            False,
            {
                "ok": False,
                "ready": False,
                "action": "failed",
                "zjxiezuo_running": running,
                "message": hint,
            },
        )


def main():
    parser = argparse.ArgumentParser(description="紫金私网 WPS 365 环境检查与导入")
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("status", help="检查环境并校验接口")
    ensure = sub.add_parser("ensure", help="缺凭证或会话失效时从紫金协作导入")
    ensure.add_argument(
        "--refresh",
        action="store_true",
        help="即使已有环境变量，也重新从紫金协作导入并校验",
    )
    args = parser.parse_args()

    try:
        sidecar_mod = _load_sidecar_mod()
    except Exception as exc:
        print(json.dumps({"ok": False, "message": str(exc)}, ensure_ascii=False, indent=2))
        return 1

    if args.cmd == "status":
        return cmd_status(sidecar_mod)
    return cmd_ensure(sidecar_mod, args.refresh)


if __name__ == "__main__":
    sys.exit(main())
